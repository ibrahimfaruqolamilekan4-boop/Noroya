// Builds the Vercel serverless function from api/function-entry.js + server.ts
// and every local/node dependency into ONE self-contained ESM file at
// api/index.js.
//
// Why: Vercel's current Node runtime executes TypeScript functions by serving
// the raw source through Node's native type-stripping instead of bundling.
// In that mode, server.ts's import graph (src/lib/*.ts, backend/*.js, npm
// packages) must all be traced and shipped alongside it — and that tracing is
// exactly what broke in production (ERR_MODULE_NOT_FOUND at function load time
// => every /api route 500s with FUNCTION_INVOCATION_FAILED, with no way to
// even run the try/catch inside the handler).
//
// Pre-bundling with esbuild at build time removes all of that fragility: the
// function is a single plain-JS ESM file, local dependency graph resolved and
// inlined. `../server.ts` specifiers, `.js`-vs-`.ts` resolution and Vercel
// tracing semantics no longer matter at runtime.
//
// DO NOT edit api/index.js by hand — edit api/function-entry.js / server.ts
// and re-run: node scripts/build-function.mjs
import { build } from 'esbuild';

await build({
  entryPoints: ['api/function-entry.js'],
  outfile: 'api/index.js',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  // Local code (server.ts, src/lib, backend/) is inlined; npm packages stay
  // as plain external requires/import — the classic Vercel tracing path for
  // a .js entry, which is battle-tested.
  packages: 'external',
  banner: {
    js: [
      '// AUTO-GENERATED by scripts/build-function.mjs -- DO NOT EDIT.',
      '// Source: api/function-entry.js + server.ts (local imports inlined).',
      '// Rebuild: npm run build:function',
    ].join('\n'),
  },
  logLevel: 'warning',
  metafile: true,
}).then((result) => {
  const out = Object.entries(result.metafile.outputs)[0];
  const inputs = Object.keys(out[1].inputs).filter((p) => !p.includes('node_modules'));
  console.log(
    `[build-function] api/index.js: ${(out[1].bytes / 1024 / 1024).toFixed(1)} MB ` +
    `(${inputs.length} local files inlined: ${inputs.join(', ')})`
  );
});
